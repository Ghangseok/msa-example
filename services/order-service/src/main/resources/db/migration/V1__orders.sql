-- 주문 서비스의 시퀀스와 테이블. specs/001-place-order/data-model.md 2절을 그대로 옮겼다.
-- 이미 적용된 마이그레이션 파일은 고치지 않고, 바꿀 것이 생기면 새 파일을 더한다.

-- 주문 번호를 만든다. 인스턴스가 2개일 때 번호에 빈칸이 생겨도 문제는 없지만, 테스트에서 번호를 읽기 쉽게 캐시를 쓰지 않는다.
CREATE SEQUENCE ORDERS_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE ORDERS (
    ORDER_NO       NUMBER(19)    NOT NULL,
    CUSTOMER_ID    VARCHAR2(255) NOT NULL,
    REQUEST_KEY    VARCHAR2(36)  NOT NULL,
    STATUS         VARCHAR2(20)  NOT NULL,
    REASON         VARCHAR2(30),
    RELEASE_STATUS VARCHAR2(20),
    CREATED_AT     TIMESTAMP     NOT NULL,
    UPDATED_AT     TIMESTAMP     NOT NULL,
    CONSTRAINT PK_ORDERS PRIMARY KEY (ORDER_NO),
    -- 같은 고객의 같은 키는 주문 하나다. 다른 고객의 같은 키는 별개다.
    CONSTRAINT UK_ORDERS_CUSTOMER_KEY UNIQUE (CUSTOMER_ID, REQUEST_KEY),
    CONSTRAINT CK_ORDERS_STATUS CHECK (STATUS IN ('PENDING', 'CONFIRMED', 'REJECTED', 'FAILED')),
    CONSTRAINT CK_ORDERS_REASON CHECK (REASON IS NULL OR REASON IN ('OUT_OF_STOCK', 'PRODUCT_NOT_FOUND', 'RETRY_LATER')),
    CONSTRAINT CK_ORDERS_RELEASE_STATUS CHECK (RELEASE_STATUS IS NULL OR RELEASE_STATUS IN ('NOT_REQUIRED', 'RELEASED', 'RELEASE_FAILED'))
);

CREATE TABLE ORDER_ITEMS (
    ORDER_NO      NUMBER(19)   NOT NULL,
    PRODUCT_ID    VARCHAR2(20) NOT NULL,
    QUANTITY      NUMBER(2)    NOT NULL,
    -- 거절된 주문에서 이 상품이 부족했으면 OUT_OF_STOCK, 없었으면 PRODUCT_NOT_FOUND다. 그 밖에는 비어 있다.
    REJECT_REASON VARCHAR2(20),
    -- 같은 상품은 한 주문에 한 줄만 들어간다.
    CONSTRAINT PK_ORDER_ITEMS PRIMARY KEY (ORDER_NO, PRODUCT_ID),
    CONSTRAINT FK_ORDER_ITEMS_ORDERS FOREIGN KEY (ORDER_NO) REFERENCES ORDERS (ORDER_NO),
    CONSTRAINT CK_ORDER_ITEMS_QTY CHECK (QUANTITY BETWEEN 1 AND 99)
);
